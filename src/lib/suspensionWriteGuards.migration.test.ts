import { PGlite } from '@electric-sql/pglite';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

const OWNER = '10000000-0000-4000-8000-000000000001';
const OTHER_OWNER = '10000000-0000-4000-8000-000000000002';
const COLLABORATOR = '10000000-0000-4000-8000-000000000003';
const MIGRATION = readFileSync(
  new URL('../../supabase/migrations/20261103225950_platform_suspension_write_guards.sql', import.meta.url),
  'utf8',
);

let db: PGlite;

async function setup() {
  db = new PGlite();
  await db.exec(`
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE ROLE service_role;
    CREATE SCHEMA auth;
    CREATE SCHEMA storage;
    CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql STABLE AS $$
      SELECT nullif(current_setting('request.jwt.claim.role', true), '')
    $$;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
      SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
    $$;
    CREATE TABLE public.profiles (id uuid PRIMARY KEY);
    CREATE TABLE public.collaborators (
      owner_uid uuid NOT NULL, user_uid uuid, revoked_at timestamptz
    );
    CREATE TABLE public.business_subscriptions (
      owner_uid uuid PRIMARY KEY, status text NOT NULL DEFAULT 'active'
    );
    CREATE TABLE public.user_rows (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id uuid);
    CREATE TABLE public.owner_rows (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_uid uuid);
    CREATE TABLE public.mixed_rows (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id uuid, owner_uid uuid
    );
    CREATE TABLE public.unowned_rows (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label text);
    CREATE TABLE storage.objects (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      bucket_id text NOT NULL, name text NOT NULL, owner uuid, owner_id text
    );

    CREATE FUNCTION public.get_owner_uid(v_uid uuid) RETURNS uuid
      LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
        SELECT coalesce((SELECT owner_uid FROM public.collaborators
          WHERE user_uid=v_uid AND revoked_at IS NULL LIMIT 1), v_uid)
      $$;
    CREATE FUNCTION public.business_require_active(p_owner uuid) RETURNS void
      LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
        BEGIN
          IF EXISTS (SELECT 1 FROM public.business_subscriptions
            WHERE owner_uid=p_owner AND status='suspended') THEN
            RAISE EXCEPTION 'La cuenta del negocio está suspendida. Comunicate con RivaTech.';
          END IF;
        END
      $$;
    CREATE FUNCTION public.is_platform_admin() RETURNS boolean
      LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
        SELECT coalesce(current_setting('test.platform_admin', true), 'false') = 'true'
      $$;

    INSERT INTO public.profiles (id) VALUES ('${OWNER}'), ('${OTHER_OWNER}'), ('${COLLABORATOR}');
    INSERT INTO public.collaborators (owner_uid, user_uid) VALUES ('${OWNER}', '${COLLABORATOR}');
    INSERT INTO public.business_subscriptions (owner_uid, status) VALUES
      ('${OWNER}', 'active'), ('${OTHER_OWNER}', 'active');
    GRANT USAGE ON SCHEMA public, storage, auth TO anon, authenticated, service_role;
    GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO anon, authenticated, service_role;
    GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA storage TO anon, authenticated, service_role;
    GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
    GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA storage TO anon, authenticated, service_role;
  `);
  await db.exec(MIGRATION);
}

async function expectSuspended(query: string) {
  await db.exec(`BEGIN;
    SET LOCAL ROLE authenticated;
    SELECT set_config('request.jwt.claim.role', 'authenticated', true);
    SELECT set_config('request.jwt.claim.sub', '${OWNER}', true);
  `);
  try {
    await expect(db.query(query)).rejects.toThrow('La cuenta del negocio está suspendida. Comunicate con RivaTech.');
  } finally {
    await db.exec('ROLLBACK;');
  }
}

describe('business suspension write guards migration', () => {
  beforeEach(setup);
  afterEach(async () => { await db.close(); });

  it('installs a write trigger on every public base table identified by information_schema', async () => {
    const uncovered = await db.query<{ table_name: string; owner_column: string }>(`
      SELECT DISTINCT c.table_name, c.column_name AS owner_column
      FROM information_schema.columns c
      JOIN information_schema.tables t
        ON t.table_schema=c.table_schema AND t.table_name=c.table_name
      WHERE c.table_schema='public'
        AND c.column_name IN ('user_id','owner_uid')
        AND t.table_type='BASE TABLE'
        AND NOT EXISTS (
          SELECT 1 FROM information_schema.triggers tr
          WHERE tr.event_object_schema=c.table_schema AND tr.event_object_table=c.table_name
            AND tr.trigger_name='suspension_write_guard'
        )
      ORDER BY c.table_name,c.column_name
    `);
    expect(uncovered.rows).toEqual([]);
    const profileTrigger = await db.query<{ count: number }>(`
      SELECT count(*)::int AS count FROM information_schema.triggers
      WHERE event_object_schema='public' AND event_object_table='profiles'
        AND trigger_name='suspension_write_guard'
    `);
    expect(profileTrigger.rows[0].count).toBe(3);
  });

  it('blocks insert, update, and delete across the generated owned-table list', async () => {
    const ownedTables = await db.query<{ table_name: string; owner_column: string }>(`
      SELECT table_name, min(column_name) AS owner_column
      FROM information_schema.columns
      WHERE table_schema='public' AND column_name IN ('user_id','owner_uid')
      GROUP BY table_name ORDER BY table_name
    `);
    for (const { table_name, owner_column } of ownedTables.rows) {
      await db.query(`INSERT INTO public."${table_name}" ("${owner_column}") VALUES ($1) ON CONFLICT DO NOTHING`, [OWNER]);
    }
    await db.exec(`BEGIN;
      SET LOCAL ROLE service_role;
      SELECT set_config('request.jwt.claim.role', 'service_role', true);
      UPDATE public.business_subscriptions SET status='suspended' WHERE owner_uid='${OWNER}';
    COMMIT;`);

    for (const { table_name, owner_column } of ownedTables.rows) {
      await expectSuspended(`INSERT INTO public."${table_name}" ("${owner_column}") VALUES ('${OWNER}') ON CONFLICT DO NOTHING`);
      await expectSuspended(`UPDATE public."${table_name}" SET "${owner_column}"='${OWNER}' WHERE "${owner_column}"='${OWNER}'`);
      await expectSuspended(`DELETE FROM public."${table_name}" WHERE "${owner_column}"='${OWNER}'`);
    }
  });

  it('maps active collaborators and Storage paths to their suspended owner', async () => {
    await db.exec(`BEGIN;
      SET LOCAL ROLE service_role;
      SELECT set_config('request.jwt.claim.role', 'service_role', true);
      UPDATE public.business_subscriptions SET status='suspended' WHERE owner_uid='${OWNER}';
      INSERT INTO storage.objects (bucket_id,name,owner_id)
        VALUES ('assets','${OWNER}/photos/one.webp','${COLLABORATOR}');
    COMMIT;`);

    await expectSuspended(`INSERT INTO storage.objects (bucket_id,name,owner_id)
      VALUES ('assets','${OWNER}/photos/two.webp','${COLLABORATOR}')`);
    await expectSuspended(`UPDATE storage.objects SET name='${OWNER}/photos/renamed.webp'
      WHERE name='${OWNER}/photos/one.webp'`);
    await expectSuspended(`DELETE FROM storage.objects WHERE name='${OWNER}/photos/one.webp'`);
    await expectSuspended(`UPDATE public.profiles SET id='${OTHER_OWNER}' WHERE id='${OWNER}'`);
  });

  it('allows service-role work and platform admins to manage a suspended business', async () => {
    await db.exec(`BEGIN;
      SET LOCAL ROLE service_role;
      SELECT set_config('request.jwt.claim.role', 'service_role', true);
      UPDATE public.business_subscriptions SET status='suspended' WHERE owner_uid='${OWNER}';
      INSERT INTO public.user_rows (user_id) VALUES ('${OWNER}');
      INSERT INTO storage.objects (bucket_id,name,owner_id)
        VALUES ('assets','${OWNER}/photos/service.webp','${OWNER}');
    COMMIT;`);

    await db.exec(`BEGIN;
      SET LOCAL ROLE authenticated;
      SELECT set_config('request.jwt.claim.role', 'authenticated', true);
      SELECT set_config('request.jwt.claim.sub', '${OTHER_OWNER}', true);
      SELECT set_config('test.platform_admin', 'true', true);
      UPDATE public.business_subscriptions SET status='active' WHERE owner_uid='${OWNER}';
      COMMIT;`);
    const status = await db.query<{ status: string }>(
      `SELECT status FROM public.business_subscriptions WHERE owner_uid='${OWNER}'`,
    );
    expect(status.rows[0].status).toBe('active');
  });
});
